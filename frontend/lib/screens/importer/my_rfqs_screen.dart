/// Quotations received against one RFQ — importer accepts one, which creates the order +
/// escrow. Unchanged from before (same TradeService calls, same accept flow).
class RFQQuotationsScreen extends StatefulWidget {
  final RFQ rfq;
  const RFQQuotationsScreen({super.key, required this.rfq});
  @override
  State<RFQQuotationsScreen> createState() => _RFQQuotationsScreenState();
}

class _RFQQuotationsScreenState extends State<RFQQuotationsScreen> {
  final _tradeService = TradeService();
  final _negotiationService = NegotiationService();
  late Future<List<Quotation>> _future;
  bool _accepting = false;

  @override
  void initState() {
    super.initState();
    _future = _tradeService.listQuotationsForRFQ(widget.rfq.id);
  }

  void _refresh() => setState(() => _future = _tradeService.listQuotationsForRFQ(widget.rfq.id));

  // Unchanged from before — same TradeService call, same accept flow, same order creation.
  Future<void> _accept(Quotation q) async {
    setState(() => _accepting = true);
    try {
      final order = await _tradeService.acceptQuotation(q.id);
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(content: Text('Order ${order.orderNumber} created. Go to your dashboard to pay into escrow.'), backgroundColor: AppColors.success),
        );
        Navigator.of(context).pop();
      }
    } catch (e) {
      if (mounted) ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text('$e'), backgroundColor: AppColors.error));
    } finally {
      if (mounted) setState(() => _accepting = false);
    }
  }

  // New — Negotiation Engine entry points. Purely additive: neither touches the quotation
  // accept flow above, both go through the new /negotiations/* endpoints only.
  Future<void> _reject(Quotation q) async {
    setState(() => _accepting = true);
    try {
      await _negotiationService.rejectQuotation(q.id);
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(const SnackBar(content: Text('Quotation rejected'), backgroundColor: AppColors.success));
        _refresh();
      }
    } catch (e) {
      if (mounted) ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text('$e'), backgroundColor: AppColors.error));
    } finally {
      if (mounted) setState(() => _accepting = false);
    }
  }

  Future<void> _negotiate(Quotation q) async {
    setState(() => _accepting = true);
    try {
      final negotiation = await _negotiationService.start(q.id);
      if (mounted) {
        await Navigator.of(context).push(MaterialPageRoute(builder: (_) => NegotiationScreen(negotiationId: negotiation.id, rfq: widget.rfq)));
        _refresh();
      }
    } catch (e) {
      if (mounted) ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text('$e'), backgroundColor: AppColors.error));
    } finally {
      if (mounted) setState(() => _accepting = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: Text(widget.rfq.rfqNumber)),
      body: FutureBuilder<List<Quotation>>(
        future: _future,
        builder: (context, snapshot) {
          if (snapshot.connectionState == ConnectionState.waiting) {
            return const Center(child: CircularProgressIndicator());
          }
          if (snapshot.hasError) {
            return Center(child: Text('Error: ${snapshot.error}'));
          }
          final quotations = snapshot.data ?? [];
          if (quotations.isEmpty) {
            return const Center(child: Text('No quotations received yet.', style: TextStyle(color: AppColors.textSecondary)));
          }
          return ListView.builder(
            padding: const EdgeInsets.all(16),
            itemCount: quotations.length,
            itemBuilder: (context, i) {
              final q = quotations[i];
              return Card(
                margin: const EdgeInsets.only(bottom: 12),
                child: Padding(
                  padding: const EdgeInsets.all(14),
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Row(
                        mainAxisAlignment: MainAxisAlignment.spaceBetween,
                        children: [
                          Text('₹${q.unitPrice.toStringAsFixed(2)} / unit', style: const TextStyle(fontWeight: FontWeight.w700, fontSize: 16)),
                          Chip(label: Text(statusLabel(q.status)), backgroundColor: statusColor(q.status).withValues(alpha: 0.12), labelStyle: TextStyle(color: statusColor(q.status))),
                        ],
                      ),
                      const SizedBox(height: 6),
                      Text('Total: ₹${q.totalAmount.toStringAsFixed(2)} · Qty: ${q.quantity}', style: const TextStyle(color: AppColors.textSecondary)),
                      Text('Valid until: ${q.validityDate.toLocal().toString().split(' ').first}', style: const TextStyle(color: AppColors.textSecondary, fontSize: 13)),
                      if (q.terms != null && q.terms!.isNotEmpty) ...[
                        const SizedBox(height: 6),
                        Text(q.terms!),
                      ],
                      if (q.status == 'pending') ...[
                        const SizedBox(height: 10),
                        SizedBox(
                          width: double.infinity,
                          child: ElevatedButton(
                            onPressed: _accepting ? null : () => _accept(q),
                            child: const Text('Accept Quotation'),
                          ),
                        ),
                        const SizedBox(height: 8),
                        Row(
                          children: [
                            Expanded(
                              child: OutlinedButton(
                                onPressed: _accepting ? null : () => _reject(q),
                                style: OutlinedButton.styleFrom(foregroundColor: AppColors.error, side: const BorderSide(color: AppColors.error)),
                                child: const Text('Reject'),
                              ),
                            ),
                            const SizedBox(width: 8),
                            Expanded(
