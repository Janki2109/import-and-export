                      tooltip: 'Download',
                      icon: const Icon(Icons.download_outlined, size: 18, color: AppColors.primary),
                      onSelected: (v) {
                        switch (v) {
                          case 'pdf': onDownloadPdf(); break;
                          case 'docx': onDownloadDocx(); break;
                          case 'image': onDownloadImage(); break;
                        }
                      },
                      itemBuilder: (context) => const [
                        PopupMenuItem(value: 'pdf', child: Text('Download PDF')),
                        PopupMenuItem(value: 'docx', child: Text('Download DOCX')),
