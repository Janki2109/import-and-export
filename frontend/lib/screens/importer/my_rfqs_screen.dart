/// Importer's posted RFQs — tap one to view quotations received and accept the best offer.
/// The underlying data source is still TradeService.listMyRFQs(); search/filter/sort below
/// are all done client-side over that same list — no new endpoints.
class MyRFQsScreen extends ConsumerStatefulWidget {
  const MyRFQsScreen({super.key});
  @override
  ConsumerState<MyRFQsScreen> createState() => _MyRFQsScreenState();
}

enum _SortOrder { newest, oldest }

class _MyRFQsScreenState extends ConsumerState<MyRFQsScreen> {
  final _tradeService = TradeService();
  late Future<List<RFQ>> _future;
  final _searchCtrl = TextEditingController();
  String _query = '';
  String _statusFilter = 'All';
  _SortOrder _sort = _SortOrder.newest;

  static const _statuses = ['All', 'open', 'quoted', 'closed', 'cancelled'];

  @override
  void initState() {
    super.initState();
    _future = _tradeService.listMyRFQs();
  }

  void _refresh() => setState(() => _future = _tradeService.listMyRFQs());

  List<RFQ> _applyFilters(List<RFQ> rfqs) {
    var list = rfqs.where((r) {
      if (_statusFilter != 'All' && r.status != _statusFilter) return false;
      if (_query.trim().isEmpty) return true;
      final q = _query.trim().toLowerCase();
      return r.productName.toLowerCase().contains(q) || r.rfqNumber.toLowerCase().contains(q) || r.destinationCountry.toLowerCase().contains(q);
    }).toList();
    list.sort((a, b) => _sort == _SortOrder.newest ? b.createdAt.compareTo(a.createdAt) : a.createdAt.compareTo(b.createdAt));
    return list;
  }

  RfqReportData _reportDataFor(RFQ rfq) {
    final auth = ref.read(authProvider);
    return RfqReportData(
      rfqNumber: rfq.rfqNumber,
      issueDate: '${rfq.createdAt.toLocal()}'.split('.').first,
      status: rfq.status[0].toUpperCase() + rfq.status.substring(1),
      buyerName: auth.currentUser?.fullName ?? '',
      buyerCompany: auth.currentUser?.companyName ?? 'Not specified',
      buyerEmail: auth.currentUser?.email ?? '',
      supplierName: rfq.status == 'quoted' || rfq.status == 'closed' ? 'See quotations for assigned supplier' : 'To be assigned (open RFQ)',
      productName: rfq.productName,
      hsnCode: rfq.hsnCode ?? 'Not specified',
      category: 'Not specified',
      productDescription: rfq.description ?? 'Not specified',
      quantity: rfq.quantity.toString(),
      unit: rfq.unit,
      minOrderQty: 'Not specified',
      packagingType: 'Not specified',
      targetPrice: rfq.targetPrice?.toStringAsFixed(2) ?? 'Not specified',
      currency: 'INR',
      incoterm: 'Not specified',
      originCountry: 'Not specified',
      destinationCountry: rfq.destinationCountry,
      shippingMode: 'Not specified',
      deliveryDeadline: 'Not specified',
      qualityRequirements: '',
      certifications: '',
      inspectionRequired: false,
      packagingInstructions: '',
      additionalNotes: '',
    );
  }

  Future<void> _duplicate(RFQ rfq) async {
    final created = await Navigator.of(context).push<bool>(
      MaterialPageRoute(builder: (_) => CreateRFQScreen(duplicateFrom: _reportDataFor(rfq))),
    );
    if (created == true) _refresh();
  }

  Future<void> _share(RFQ rfq) async {
    final d = _reportDataFor(rfq);
    await Share.share('''
RFQ ${d.rfqNumber}
Product: ${d.productName}
Quantity: ${d.quantity} ${d.unit}
Target Price: ${d.targetPrice}
Destination: ${d.destinationCountry}
Status: ${d.status}

Generated by ${AppConstants.appName}
''');
  }

  Future<void> _downloadPdf(RFQ rfq) async {
    final bytes = await buildRfqReportPdf(_reportDataFor(rfq), title: 'RFQ Report');
    await Printing.layoutPdf(onLayout: (_) async => bytes, name: 'rfq-${rfq.rfqNumber}.pdf');
  }

  Future<void> _downloadDocx(RFQ rfq) async {
    final d = _reportDataFor(rfq);
    final bytes = buildRfqDocx(
      title: 'RFQ Report',
      companyName: AppConstants.appName,
      rfqNumber: d.rfqNumber,
      issueDate: d.issueDate,
      fields: [
        RfqDocxField('Buyer', '${d.buyerName} (${d.buyerCompany})'),
        RfqDocxField('Product Name', d.productName),
        RfqDocxField('HS Code', d.hsnCode),
        RfqDocxField('Quantity', '${d.quantity} ${d.unit}'),
        RfqDocxField('Target Price', d.targetPrice),
        RfqDocxField('Destination', d.destinationCountry),
        RfqDocxField('Status', d.status),
      ],
      termsAndConditions: RfqReportData.termsAndConditions,
      footer: 'Generated by ${AppConstants.appName}',
    );
    final dir = await getTemporaryDirectory();
    final file = File('${dir.path}/rfq-${d.rfqNumber}.docx');
    await file.writeAsBytes(bytes);
    await Share.shareXFiles([XFile(file.path)], text: 'RFQ ${d.rfqNumber}');
  }

  Future<void> _downloadImage(RFQ rfq) async {
    final key = GlobalKey();
    final overlay = OverlayEntry(
      builder: (ctx) => Positioned(
        left: -2000,
        child: Material(
          child: RepaintBoundary(
            key: key,
            child: SizedBox(width: 380, child: _RfqDocumentPreview(data: _reportDataFor(rfq))),
          ),
        ),
      ),
    );
    Overlay.of(context).insert(overlay);
    await Future.delayed(const Duration(milliseconds: 50));
    try {
      final boundary = key.currentContext!.findRenderObject() as RenderRepaintBoundary;
      final image = await boundary.toImage(pixelRatio: 3.0);
      final byteData = await image.toByteData(format: ui.ImageByteFormat.png);
      final bytes = byteData!.buffer.asUint8List();
      await Gal.requestAccess();
      await Gal.putImageBytes(bytes, name: 'rfq-${rfq.rfqNumber}');
      if (mounted) ScaffoldMessenger.of(context).showSnackBar(const SnackBar(content: Text('Report Saved Successfully'), backgroundColor: AppColors.success));
    } catch (e) {
      if (mounted) ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text('Could not save image: $e'), backgroundColor: AppColors.error));
    } finally {
      overlay.remove();
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: const Text('My RFQs')),
      floatingActionButton: FloatingActionButton.extended(
        onPressed: () async {
          final created = await Navigator.of(context).push<bool>(MaterialPageRoute(builder: (_) => const CreateRFQScreen()));
          if (created == true) _refresh();
        },
        icon: const Icon(Icons.add),
        label: const Text('New RFQ'),
      ),
      body: RefreshIndicator(
        onRefresh: () async => _refresh(),
        child: FutureBuilder<List<RFQ>>(
          future: _future,
          builder: (context, snapshot) {
            if (snapshot.connectionState == ConnectionState.waiting) {
              return const Center(child: CircularProgressIndicator());
            }
            if (snapshot.hasError) {
              return Center(child: Text('Error: ${snapshot.error}'));
            }
            final all = snapshot.data ?? [];
            final rfqs = _applyFilters(all);

            return CustomScrollView(
              slivers: [
                SliverToBoxAdapter(
                  child: Padding(
                    padding: const EdgeInsets.fromLTRB(16, 16, 16, 0),
                    child: TextField(
                      controller: _searchCtrl,
                      onChanged: (v) => setState(() => _query = v),
                      decoration: InputDecoration(
                        hintText: 'Search by product, RFQ number, or destination',
                        prefixIcon: const Icon(Icons.search),
                        suffixIcon: _query.isNotEmpty
                            ? IconButton(icon: const Icon(Icons.close, size: 18), onPressed: () { _searchCtrl.clear(); setState(() => _query = ''); })
                            : null,
                      ),
                    ),
                  ),
                ),
                SliverToBoxAdapter(
                  child: Padding(
                    padding: const EdgeInsets.fromLTRB(16, 12, 16, 4),
                    child: Row(
                      children: [
                        Expanded(
                          child: SizedBox(
                            height: 40,
                            child: ListView.separated(
                              scrollDirection: Axis.horizontal,
                              itemCount: _statuses.length,
                              separatorBuilder: (_, __) => const SizedBox(width: 8),
                              itemBuilder: (context, i) {
                                final s = _statuses[i];
                                final selected = _statusFilter == s;
                                return ChoiceChip(
                                  label: Text(s == 'All' ? 'All' : statusLabel(s)),
                                  selected: selected,
                                  onSelected: (_) => setState(() => _statusFilter = s),
                                  selectedColor: AppColors.primary,
                                  labelStyle: TextStyle(color: selected ? Colors.white : AppColors.textPrimary, fontSize: 12.5, fontWeight: FontWeight.w600),
                                );
                              },
                            ),
                          ),
                        ),
                        const SizedBox(width: 8),
                        PopupMenuButton<_SortOrder>(
                          icon: const Icon(Icons.sort),
                          tooltip: 'Sort',
                          onSelected: (v) => setState(() => _sort = v),
                          itemBuilder: (context) => const [
                            PopupMenuItem(value: _SortOrder.newest, child: Text('Newest first')),
                            PopupMenuItem(value: _SortOrder.oldest, child: Text('Oldest first')),
                          ],
                        ),
                      ],
                    ),
                  ),
                ),
                if (rfqs.isEmpty)
                  SliverFillRemaining(
                    hasScrollBody: false,
                    child: Center(
                      child: Padding(
                        padding: const EdgeInsets.all(32),
                        child: Column(
                          mainAxisSize: MainAxisSize.min,
                          children: [
                            Container(
                              width: 72,
                              height: 72,
                              decoration: BoxDecoration(color: AppColors.primary.withValues(alpha: 0.08), shape: BoxShape.circle),
                              child: const Icon(Icons.request_quote_outlined, size: 34, color: AppColors.primary),
                            ),
                            const SizedBox(height: 16),
                            Text(all.isEmpty ? 'No RFQs yet' : 'No matching RFQs', style: const TextStyle(fontWeight: FontWeight.w700, fontSize: 16)),
                            const SizedBox(height: 6),
                            Text(
                              all.isEmpty ? 'Tap "New RFQ" to request quotes from exporters.' : 'Try a different search or filter.',
                              textAlign: TextAlign.center,
                              style: const TextStyle(color: AppColors.textSecondary),
                            ),
                          ],
                        ),
                      ),
                    ),
                  )
                else
                  SliverPadding(
                    padding: const EdgeInsets.fromLTRB(16, 8, 16, 96),
                    sliver: SliverList.builder(
                      itemCount: rfqs.length,
                      itemBuilder: (context, i) => _RfqCard(
                        rfq: rfqs[i],
                        onView: () => Navigator.of(context).push(MaterialPageRoute(builder: (_) => RFQQuotationsScreen(rfq: rfqs[i]))),
                        onDuplicate: () => _duplicate(rfqs[i]),
                        onShare: () => _share(rfqs[i]),
                        onDownloadPdf: () => _downloadPdf(rfqs[i]),
                        onDownloadDocx: () => _downloadDocx(rfqs[i]),
                        onDownloadImage: () => _downloadImage(rfqs[i]),
                      ),
                    ),
                  ),
              ],
            );
          },
        ),
      ),
    );
  }
}

Color _rfqStatusColor(String status) {
  switch (status) {
    case 'open':
      return AppColors.heldBlue;
    case 'quoted':
      return AppColors.accent;
    case 'closed':
      return AppColors.success;
    case 'cancelled':
      return AppColors.error;
    default:
      return AppColors.textSecondary;
  }
}

/// Premium RFQ card — product, RFQ number, destination, quantity, target price, status
