                          Text('${rfq.rfqNumber} · ${rfq.destinationCountry}', style: const TextStyle(color: AppColors.textSecondary, fontSize: 12)),
                        ],
                      ),
                    ),
                    Container(
                      padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 4),
                      decoration: BoxDecoration(color: color.withValues(alpha: 0.12), borderRadius: BorderRadius.circular(20)),
                      child: Text(statusLabel(rfq.status), style: TextStyle(color: color, fontWeight: FontWeight.w700, fontSize: 11)),
                    ),
                  ],
                ),
                const SizedBox(height: 10),
                Row(
                  children: [
                    Expanded(child: _stat('Quantity', '${rfq.quantity.toStringAsFixed(0)} ${rfq.unit}')),
                    Expanded(child: _stat('Target Price', rfq.targetPrice != null ? '₹${rfq.targetPrice!.toStringAsFixed(2)}' : 'Not set')),
                    Expanded(child: _stat('Created', _formatDate(rfq.createdAt))),
                  ],
                ),
                const SizedBox(height: 10),
                Divider(height: 1, color: Colors.grey.shade200),
                const SizedBox(height: 6),
                Row(
                  children: [
                    _quickAction(Icons.visibility_outlined, 'View', onView),
                    _quickAction(Icons.copy_outlined, 'Duplicate', onDuplicate),
                    _quickAction(Icons.share_outlined, 'Share', onShare),
